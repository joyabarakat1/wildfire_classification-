"""FPA FOD v6: California loading, EDA, and train/validation baselines.
Shared data loader and optional scikit-learn baselines.
Reported proposal results are generated by train_numpy_baselines.py.
"""
from pathlib import Path
import argparse, hashlib, json, sqlite3, sys
import numpy as np
import pandas as pd
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
from sklearn.dummy import DummyClassifier
from sklearn.compose import ColumnTransformer
from sklearn.preprocessing import OneHotEncoder, StandardScaler
from sklearn.pipeline import Pipeline
from sklearn.linear_model import LogisticRegression
from sklearn.ensemble import RandomForestClassifier
from sklearn.metrics import accuracy_score, balanced_accuracy_score, f1_score, precision_recall_fscore_support

def load_data(path):
    with sqlite3.connect(f"file:{path.resolve().as_posix()}?mode=ro", uri=True) as con:
        available={r[1] for r in con.execute("PRAGMA table_info(Fires)")}
        required={"FOD_ID","STATE","FIRE_YEAR","DISCOVERY_DOY","LATITUDE","LONGITUDE","NWCG_CAUSE_CLASSIFICATION"}
        if not required <= available:
            raise ValueError(f"Expected sixth-edition Fires schema; missing {required-available}. Do not silently use another edition.")
        cols=sorted(required | ({"NWCG_GENERAL_CAUSE"} & available))
        frame=pd.read_sql_query("SELECT "+",".join(cols)+" FROM Fires WHERE STATE = ?", con, params=["CA"])
    audit={"raw_california":len(frame),"raw_missing":frame.isna().sum().to_dict(),
           "raw_cause_classification":frame.NWCG_CAUSE_CLASSIFICATION.value_counts(dropna=False).to_dict()}
    if frame.FOD_ID.isna().any(): raise ValueError("Missing record IDs")
    audit["duplicate_ids"]=int(frame.FOD_ID.duplicated().sum())
    frame=frame.drop_duplicates("FOD_ID").copy()
    label=frame.NWCG_CAUSE_CLASSIFICATION.astype("string").str.strip().str.lower()
    # Natural is a proxy, NOT a claim of a verified lightning cause.
    frame["target"]=label.map({"human":1,"natural":0})
    audit["excluded_unknown_or_unrecognized_labels"]=int(frame.target.isna().sum())
    frame=frame[frame.target.notna()].copy()
    for col in ["FIRE_YEAR","DISCOVERY_DOY","LATITUDE","LONGITUDE"]:
        frame[col]=pd.to_numeric(frame[col],errors="coerce")
    numeric=frame[["FIRE_YEAR","DISCOVERY_DOY","LATITUDE","LONGITUDE"]]
    valid=np.isfinite(numeric).all(axis=1)
    valid &= frame.FIRE_YEAR.between(1992,2020) & (frame.FIRE_YEAR%1==0)
    valid &= frame.LATITUDE.between(-90,90) & frame.LONGITUDE.between(-180,180)
    valid &= frame.DISCOVERY_DOY.between(1,366) & (frame.DISCOVERY_DOY%1==0)
    safe_year=frame.FIRE_YEAR.where(valid).astype("Int64")
    starts=pd.to_datetime(safe_year.astype("string")+"-01-01",errors="coerce")
    dates=starts+pd.to_timedelta(frame.DISCOVERY_DOY.where(valid)-1,unit="D")
    valid &= (frame.DISCOVERY_DOY%1==0) & frame.DISCOVERY_DOY.ge(1)
    valid &= dates.dt.year.eq(frame.FIRE_YEAR) & dates.notna()
    audit["excluded_invalid_features"]=int((~valid).sum())
    frame=frame.loc[valid].copy()
    frame["date"]=dates.loc[valid]
    frame["month"]=frame.date.dt.month.astype(int)
    frame["weekday"]=frame.date.dt.dayofweek.astype(int)
    frame["target"]=frame.target.astype(int)
    audit["retained"]=len(frame)
    if "NWCG_GENERAL_CAUSE" in frame:
        audit["retained_general_causes"]=frame.NWCG_GENERAL_CAUSE.value_counts(dropna=False).to_dict()
    return frame,audit

def score(y,pred):
    pr,re,f1,_=precision_recall_fscore_support(y,pred,labels=[0,1],zero_division=0)
    return {"accuracy":accuracy_score(y,pred),"balanced_accuracy":balanced_accuracy_score(y,pred),
            "macro_f1":f1_score(y,pred,labels=[0,1],average="macro",zero_division=0),
            "natural_precision":pr[0],"natural_recall":re[0],"natural_f1":f1[0],
            "human_precision":pr[1],"human_recall":re[1],"human_f1":f1[1]}

def run(path,out,include_rf=False):
    out.mkdir(parents=True,exist_ok=True)
    df,audit=load_data(path)
    splits={"Train":df[df.FIRE_YEAR<=2014],
            "Validation":df[df.FIRE_YEAR.between(2015,2017)],
            "Test":df[df.FIRE_YEAR.between(2018,2020)]}
    for name,part in splits.items():
        if part.target.nunique()!=2: raise ValueError(f"{name} does not contain both classes")
    with open(out/"audit.json","w") as handle: json.dump(audit,handle,indent=2,default=str)
    stats=[]
    for name,part in splits.items():
        stats.append({"split":name,"n":len(part),"human_n":int(part.target.sum()),
                      "natural_n":int((part.target==0).sum()),"human_pct":100*part.target.mean(),
                      "latitude_mean":part.LATITUDE.mean(),"latitude_sd":part.LATITUDE.std(),
                      "longitude_mean":part.LONGITUDE.mean(),"longitude_sd":part.LONGITUDE.std()})
    pd.DataFrame(stats).to_csv(out/"statistics.csv",index=False)
    # Plot training data only; the held-out test outcomes are not used for selection.
    tr=splits["Train"]
    fig,axes=plt.subplots(1,2,figsize=(10,3.7),layout="constrained")
    for target,name,color in [(0,"Natural (lightning proxy)","#2166ac"),(1,"Human","#b35806")]:
        counts=tr[tr.target==target].month.value_counts().reindex(range(1,13),fill_value=0)
        axes[0].plot(counts.index,counts.values,label=name,color=color,marker="o")
        sample=tr[tr.target==target].sample(n=min(3000,int((tr.target==target).sum())),random_state=42)
        axes[1].scatter(sample.LONGITUDE,sample.LATITUDE,s=2,alpha=.25,color=color,label=name)
    axes[0].set(xlabel="Discovery month",ylabel="Recorded training fires",xticks=range(1,13),title="Seasonality, 1992-2014")
    axes[1].set(xlabel="Longitude (degrees)",ylabel="Latitude (degrees)",title="Training locations (sample)")
    for ax in axes: ax.legend(fontsize=7)
    fig.savefig(out/"exploration.pdf"); fig.savefig(out/"exploration.png",dpi=180); plt.close(fig)
    models={"Majority":DummyClassifier(strategy="most_frequent")}
    def prep(location):
        transforms=[("calendar",OneHotEncoder(handle_unknown="ignore"),["month","weekday"])]
        if location: transforms.append(("coordinates",StandardScaler(),["LATITUDE","LONGITUDE"]))
        return ColumnTransformer(transforms)
    for location in [False,True]:
        name="Logistic_calendar_location" if location else "Logistic_calendar"
        models[name]=Pipeline([("prep",prep(location)),("model",LogisticRegression(max_iter=2000,C=1.,random_state=42))])
    if include_rf:
        for location in [False,True]:
            name="RF_calendar_location" if location else "RF_calendar"
            models[name]=Pipeline([("prep",prep(location)),("model",RandomForestClassifier(
                n_estimators=200,max_depth=15,min_samples_leaf=20,n_jobs=2,random_state=42))])
    features=["month","weekday","LATITUDE","LONGITUDE"]
    rows=[]
    for name,estimator in models.items():
        estimator.fit(tr[features],tr.target)
        for split in ["Train","Validation"]:
            part=splits[split]
            rows.append({"model":name,"split":split,**score(part.target,estimator.predict(part[features]))})
    metrics=pd.DataFrame(rows); metrics.to_csv(out/"baseline_metrics.csv",index=False)
    # Generate LaTeX fragments only from actual measured results.
    (out/"statistics.tex").write_text(pd.DataFrame(stats)[["split","n","human_n","natural_n","human_pct"]].to_latex(
        index=False,float_format="%.2f"),encoding="utf-8")
    (out/"baseline_metrics.tex").write_text(metrics[["model","split","accuracy","balanced_accuracy","macro_f1"]].to_latex(
        index=False,float_format="%.3f"),encoding="utf-8")
    with open(path,"rb") as handle: sha=hashlib.file_digest(handle,"sha256").hexdigest()
    (out/"provenance.json").write_text(json.dumps({"source":str(path),"sha256":sha,
        "dataset_doi":"10.2737/RDS-2013-0009.6","label":"human versus natural (lightning proxy)",
        "python":sys.version,"numpy":np.__version__,"pandas":pd.__version__,
        "test_model_metrics_computed":False},indent=2),encoding="utf-8")
    print(metrics.to_string(index=False))
    print("No test model metrics computed. Review audit.json before using results in the proposal.")

if __name__=="__main__":
    parser=argparse.ArgumentParser()
    parser.add_argument("--database",type=Path,required=True)
    parser.add_argument("--output",type=Path,default=Path("results"))
    parser.add_argument("--include-rf",action="store_true")
    args=parser.parse_args()
    run(args.database,args.output,args.include_rf)

